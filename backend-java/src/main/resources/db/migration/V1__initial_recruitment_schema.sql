CREATE TABLE users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(255) NOT NULL UNIQUE,
    password VARCHAR(255) NOT NULL,
    role ENUM('ROLE_ADMIN', 'ROLE_RECRUITER') NOT NULL
);

CREATE TABLE jobs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title VARCHAR(255) NOT NULL,
    description TEXT,
    created_at TIMESTAMP
);

CREATE TABLE candidates (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255) NOT NULL,
    email VARCHAR(255),
    resume_file_path VARCHAR(255),
    job_id BIGINT NOT NULL REFERENCES jobs(id),
    ai_score DOUBLE PRECISION,
    ai_feedback TEXT,
    stage VARCHAR(255) NOT NULL,
    decision_reason TEXT,
    created_at TIMESTAMP
);

CREATE TABLE review_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    candidate_id BIGINT NOT NULL,
    actor VARCHAR(255) NOT NULL,
    from_stage VARCHAR(255) NOT NULL,
    to_stage VARCHAR(255) NOT NULL,
    reason TEXT NOT NULL,
    occurred_at TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX ix_candidates_job ON candidates(job_id);
CREATE INDEX ix_review_events_candidate ON review_events(candidate_id);
